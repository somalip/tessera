"""Generate contract types and embed the schemas for extension validation."""
import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]


def emit(schema: dict[str, Any], name: str, python: bool, classes: list[str]) -> str:
    if "const" in schema or "enum" in schema:
        values = schema.get("enum", [schema.get("const")])
        literals = [json.dumps(value) for value in values]
        return f"Literal[{', '.join(literals)}]" if python else " | ".join(literals)
    kind = schema["type"]
    if kind == "object":
        fields = [(field, emit(child, name + "_" + field, python, classes))
                  for field, child in schema["properties"].items()]
        if python:
            classes.append(f"class {name}(TypedDict):\n" + "\n".join(
                f"    {field}: {kind}" for field, kind in fields))
            return name
        return "{ " + "; ".join(f"{field}: {kind}" for field, kind in fields) + " }"
    if kind == "array":
        item = emit(schema["items"], name + "_item", python, classes)
        return f"list[{item}]" if python else f"Array<{item}>"
    if kind == "integer":
        return "int" if python else "number"
    if kind == "string":
        return "str" if python else "string"
    raise ValueError(f"Unsupported type: {schema}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schemas = [json.loads(path.read_text()) for path in sorted((ROOT / "schemas").glob("*.json"))]
    python_types: list[str] = []
    typescript = ["// Generated by tools/generate_contracts.py."]
    for schema in schemas:
        name = schema["title"]
        emit(schema, name, True, python_types)
        typescript.append(f"export type {name} = {emit(schema, name, False, [])};")
        typescript.append(f"export const {name.lower()}Schema = {json.dumps(schema, indent=2)};")
    outputs = {
        "tools/contracts.py": '"""Generated by tools/generate_contracts.py."""\n'
        "from typing import Literal, TypedDict\n\n\n" + "\n\n\n".join(python_types) + "\n",
        "vscode-extension/src/contracts.ts": "\n\n".join(typescript) + "\n",
    }
    for filename, content in outputs.items():
        path = ROOT / filename
        if args.check:
            if path.read_text() != content:
                parser.error(f"Generated output is stale: {filename}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
